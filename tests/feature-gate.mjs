import assert from 'node:assert/strict';
import {PILOT,featureForPath,validateFlags,availability,defaultFlags} from '../lib/feature-gate/policy.js';
const live=defaultFlags(),blocked={...live,'brain-rv-road-trip-mayhem':'coming_soon'};
assert.ok((()=>featureForPath('/brain-arcade/rv-road-trip-mayhem/')==='brain-rv-road-trip-mayhem')(),"canonical");
assert.ok((()=>featureForPath('/brain-arcade/chess')==='brain-chess')(),"no slash");
assert.ok((()=>featureForPath('/brain-arcade/sudoku/index.html')==='brain-sudoku')(),"index alias");
assert.ok((()=>featureForPath('/brain-arcade/chess/script.js')==='brain-chess')(),"asset");
assert.ok((()=>featureForPath('/brain-arcade/%63hess/')==='brain-chess')(),"encoded");
assert.ok((()=>featureForPath('/brain-arcade/chess-other/')===null)(),"near match");
assert.ok((()=>featureForPath('/mini-games/shared/foo.js')===null)(),"shared library");
assert.ok((()=>featureForPath('/brain-arcade/word-search/')===null)(),"other game");
assert.ok((()=>availability(validateFlags(live),'brain-chess')==='pass')(),"live");
assert.ok((()=>availability(validateFlags(blocked),'brain-rv-road-trip-mayhem')==='coming_soon')(),"blocked");
assert.ok((()=>availability(validateFlags({...live,'brain-chess':'under_improvement'}),'brain-chess')==='under_improvement')(),"temporary");
assert.ok((()=>availability(null,'brain-chess')==='unavailable')(),"fail closed");
assert.ok((()=>availability(null,null)==='pass')(),"unmapped");
assert.ok((()=>{try{validateFlags({});return false}catch{return true}})(),"missing flag");
assert.ok((()=>{try{validateFlags({...live,'brain-chess':'hidden'});return false}catch{return true}})(),"unsupported status");
console.log('15 feature-gate policy checks passed');
